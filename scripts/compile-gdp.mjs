export const toolchain = {gdpWired:'0.30.1', esbuild, typescript:ts.version};
const requireProof = (name, result) => {
  if (!result.proven || !result.checked || result.assumes) throw new Error(`${name}: proof refused ${JSON.stringify(result)}`);
};
export function checkLaws(root) {
  const decisions = [...kernelLaws(kernels), ...controlLaws(controls), ...limbLaws(limbs), singletonLaw];
  const names = [...decisions.map(law=>law.name), ...heatLaws.map(([,law])=>law.name), errorLaw.name,...streamLawNames,...seriesLawNames,...operatorLawNames,...transportLawNames,...focusLawNames,...enclosureLawNames,...normalizationLawNames].sort();
  const ledger = JSON.parse(readFileSync(join(root,'proofs/ledger.json'),'utf8'));
  if (new Set(names).size !== names.length || JSON.stringify(names) !== JSON.stringify(ledger)) throw new Error('Proof ledger mismatch: a required law is missing or duplicated');
  for (const law of decisions) {
    requireProof(law.name, proveDecision(law));
    const checked = crossCheckDecision(law, {trials:100});
    if (checked.failure) throw new Error(`${law.name}: ${checked.failure}`);
  }
  for (const [fold, law] of heatLaws) requireProof(law.name, proveFold(fold, [law]));
  requireProof(errorLaw.name, proveRatRule(errors, [errorLaw], {ms:3000}));
  return decisions.length + heatLaws.length + 1 + checkStreams() + checkSeries() + checkOperators() + checkTransport() + checkFocus() + checkEnclosures() + checkNormalization();
}
const machineSource = (name, fn) => {
  const machine = fn.rule.machine;
  if (Object.keys(machine.fns ?? {}).length) throw new Error(`${name}: foreign functions forbidden`);
  const source = compileJs(machine);
  const ast = ts.createSourceFile('machine.js',source,ts.ScriptTarget.Latest,true,ts.ScriptKind.JS);
  const exports = ast.statements.filter(s=>s.modifiers?.some(m=>m.kind===ts.SyntaxKind.ExportKeyword));
  if (ast.parseDiagnostics.length || exports.length !== 3 || exports.some(s=>!ts.isFunctionDeclaration(s)) ||
      exports.map(s=>s.name.text).join(',') !== 'init,fork,step') throw new Error('Unrecognized gdp-wired generated module');
  return `const ${name}=(()=>{\n${source.replace(/^export /gm,'')}\nreturn {init,step};\n})();\n`;
};
async function emit(machines, bridge) {
  const source = Object.entries(machines).map(([name,fn])=>machineSource(name==='disclosure'?'disclosureMachine':name,fn)).join('') + bridge;
  const result = await build({stdin:{contents:source,sourcefile:'gdp-kernel.js'},bundle:true,write:false,
    format:'esm',platform:'neutral',target:'es2022',treeShaking:true,minify:true,legalComments:'none',
    banner:{js:'// Generated by gdp-wired 0.30.1; do not edit. See proofs/ and docs/proofs.md.\n// gdp-wired generated runtime: MIT, Copyright (c) 2026 Tom X Nguyen.'}});
  const code = result.outputFiles[0].text;
  const ast = ts.createSourceFile('kernel.js',code,ts.ScriptTarget.Latest,true,ts.ScriptKind.JS);
  if (ast.parseDiagnostics.length || ast.statements.some(ts.isImportDeclaration) ||
      /\b(?:process|globalThis|console|fetch|eval|Function|require|__require)\b/.test(code)) throw new Error('Effectful runtime escaped into generated kernel');
  return code;
}
export async function compileKernel(root) {
  const abi = JSON.parse(readFileSync(join(root,'proofs/kernel-abi.json'),'utf8'));
  const expected = {disclosure:5,shownCount:2,remainingCount:2,basisStep:2};
  if (Object.keys(abi).sort().join() !== Object.keys(expected).sort().join()) throw new Error('Incompatible kernel ABI exports');
  for (const [name,arity] of Object.entries(expected)) {
    const inputType = name === 'disclosure' ? 'boolean' : 'number';
    const resultType = name === 'disclosure' ? 'DisclosureDecision' : name === 'basisStep' ? 'BasisStep' : 'number';
    if (abi[name].length-1 !== arity || abi[name].slice(0,-1).some(arg=>arg[1]!==inputType) || abi[name].at(-1)!==resultType)
      throw new Error(`Incompatible kernel ABI: ${name}`);
  }
  const types = '// Generated ABI; see proofs/kernel-abi.json.\n' + readFileSync(join(root,'proofs/kernel-types.d.ts'),'utf8')+'\n'+
    Object.entries(abi).map(([name,sig])=>`export declare function ${name}(${sig.slice(0,-1).map(([arg,type])=>`${arg}: ${type}`).join(', ')}): ${sig.at(-1)};`).join('\n')+'\n';
  return {
    'src/verified/generated/kernel.js':await emit(kernels,kernelBridge),
    'src/verified/generated/kernel.d.ts':types,
    'src/verified/generated/control.js':await emit(controls,controlBridge),
    'src/verified/generated/control.d.ts':controlTypes,
    'src/verified/generated/limbs.js':await emit(limbs,limbBridge),
    'src/verified/generated/limbs.d.ts':limbTypes,
    'src/verified/generated/streams.js':await emit(streams,streamBridge),
    'src/verified/generated/streams.d.ts':streamTypes,
  };
}
