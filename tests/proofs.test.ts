// Keep the worker's event loop available for Vitest RPCs during proof checks.
// A sequence of spawnSync calls can starve reporting even when every test passes.
const gate = (cwd: string, ...args: string[]) =>
  new Promise<{ status: number; stdout: string; stderr: string }>((resolve) => {
    execFile(
      process.execPath,
      ["--import", "tsx", "scripts/check-proofs.ts", ...args],
      { cwd, encoding: "utf8", timeout: 300000 },
      (error, stdout, stderr) => {
        resolve({
          status: error ? (typeof error.code === "number" ? error.code : 1) : 0,
          stdout,
          stderr,
        });
      },
    );
  });
const change = (dir: string, path: string, before: string, after: string) => {
  const file = join(dir, path),
    text = readFileSync(file, "utf8");
  writeFileSync(file, replaceSource(text, before, after));
};
