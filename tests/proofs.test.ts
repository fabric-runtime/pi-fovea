import { execFile } from 'node:child_process';
import { cpSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterEach, describe, expect, it } from 'vitest';
const root=fileURLToPath(new URL('../',import.meta.url));
const temporary:string[]=[];
afterEach(()=>{for(const dir of temporary.splice(0))rmSync(dir,{recursive:true,force:true});});
const fixture=()=>{
  const dir=mkdtempSync(join(tmpdir(),'fovea-gdp-'));temporary.push(dir);
  for(const path of ['proofs','scripts/check-proofs.mjs','scripts/check-lean.mjs','scripts/compile-gdp.mjs','scripts/check-streams.mjs','scripts/check-series.mjs','scripts/check-operators.mjs','scripts/check-transport.mjs','scripts/check-focus.mjs','scripts/check-enclosures.mjs','scripts/check-normalization.mjs','scripts/check-ports.mjs','scripts/prove-polynomial.mjs','src/verified','src/core/disclosure.ts','src/core/numerics.ts','src/core/interval.ts','src/core/u32.ts','src/core/heat-certificate.ts','src/core/normalization.ts','src/substrate.ts'])cpSync(join(root,path),join(dir,path),{recursive:true});
  symlinkSync(join(root,'node_modules'),join(dir,'node_modules'),'dir');return dir;
};
// Keep the worker's event loop available for Vitest RPCs during proof checks.
// A sequence of spawnSync calls can starve reporting even when every test passes.
const gate=(cwd:string,...args:string[])=>new Promise<{status:number;stdout:string;stderr:string}>(resolve=>{
  execFile(process.execPath,['scripts/check-proofs.mjs',...args],{cwd,encoding:'utf8',timeout:60000},(error,stdout,stderr)=>{
    resolve({status:error?(typeof error.code==='number'?error.code:1):0,stdout,stderr});
  });
});
const change=(dir:string,path:string,before:string,after:string)=>{
  const file=join(dir,path),text=readFileSync(file,'utf8');expect(text).toContain(before);writeFileSync(file,text.replace(before,after));
};
describe('gdp-wired proof boundary',()=>{
  it('checks byte parity and never rewrites without --write',async()=>{
    const dir=fixture(),file=join(dir,'src/verified/generated/kernel.js'),original=readFileSync(file,'utf8');
    expect((await gate(dir)).status).toBe(0);
    writeFileSync(file,original.replace('Generated by gdp-wired','TAMPERED'));
    expect((await gate(dir)).stderr).toContain('artifact is stale');expect(readFileSync(file,'utf8')).not.toBe(original);
    expect((await gate(dir,'--write')).status).toBe(0);expect(readFileSync(file,'utf8')).toBe(original);
  },180000);
  it.each([
    ['proofs/kernel.mjs','when(scope.not().or(excluded), 0,','when(scope.not().or(excluded), 2,','scope_wins'],
    ['proofs/kernel.mjs','shown: min(total, requested)','shown: total','shown_bounded_by_request'],
    ['proofs/kernel.mjs','tag: when(have.eq(0), 0,','tag: when(have.eq(0), 1,','basis_empty_refused'],
    ['proofs/heat.mjs','output:mass.mul(weightSum)','output:0','heat_transport_mass'],
    ['proofs/heat.mjs','bound:bound.plus(roundoff)','bound:bound','rounding_envelope'],
    ['proofs/controls.mjs','when(waiting.gt(0),active,active.minus(1))','active.minus(1)','semaphore_handoff_reserves_slot'],
    ['proofs/limbs.mjs','total:a.mul(b).plus(cell).plus(carry)','total:a.mul(b).plus(cell)','u16_product_cell_exact'],
    ['proofs/limbs.mjs','sticky.or(odd)','sticky','rounding_nearest_ties_even'],
    ['proofs/operators.mjs','e.B.at(k).plus(e.B.at(k.minus(1)))','e.B.at(k).plus(e.B.at(k.minus(1))).plus(1)','pascal_factorial_coefficient'],
    ['proofs/operators.mjs','one.minus(e.Q.at(e.row))','e.Q.at(e.row)','pascal_parity_adjacent'],
    ['proofs/operator-steps.mjs','posNum:e.positive','posNum:e.positive.plus(1)','stochastic_path_mass'],
    ['proofs/series.mjs','term:e.term.mul(e.n)','term:e.term.mul(e.n).plus(1)','series_tail_conservation'],
    ['proofs/series.mjs','.plus(den.mul(sd))','.plus(0)','series_all_future_prefixes_cauchy'],
    ['proofs/series.mjs','lowerSlack:when(e.checkpoint,0,e.lowerSlack)','lowerSlack:when(e.checkpoint,1,e.lowerSlack)','series_checkpoint_lower_conservation'],
    ['proofs/streams.mjs','pair=product(machine,model)',"pair=product({...machine,step:{...machine.step,state:{...machine.step.state,word:{op:'const',value:0}}}},model)",'projection_word'],
    ['proofs/streams.mjs','carry:when(take,c,carry)','carry:when(take,0,carry)','prefix_exact'],
    ['proofs/streams.mjs',".plus(term('carry').mul(term('power')))",".plus(term('carry'))",'prefix_exact'],
    ['proofs/limbs.mjs','used:when(used.plus(amount).atMost(limit),used.plus(amount),used)','used:used.plus(amount)','numeric_work_never_exceeds_limit'],
  ])('rejects broken source %s before replacing artifacts',async(path,before,after,law)=>{
    const dir=fixture(),file=join(dir,'src/verified/generated/kernel.js'),original=readFileSync(file,'utf8');
    change(dir,path,before,after);const result=await gate(dir,'--write');
    expect(result.status).toBe(1);expect(result.stderr).toContain(law);expect(readFileSync(file,'utf8')).toBe(original);
  });
  it('checks receipts without importing the prover and rejects bridge drift',async()=>{
    const dir=fixture();expect((await gate(dir,'--artifact')).status).toBe(0);
    for(const path of ['proofs/laws.mjs','proofs/kernel-abi.json','scripts/compile-gdp.mjs','scripts/prove-polynomial.mjs','proofs/series.mjs','proofs/operators.mjs','proofs/operator-steps.mjs','proofs/transport.mjs','proofs/focus.mjs','proofs/enclosures.mjs','proofs/normalization.mjs','proofs/ports.json','scripts/check-focus.mjs','scripts/check-enclosures.mjs','scripts/check-normalization.mjs','scripts/check-ports.mjs','scripts/check-transport.mjs','scripts/check-operators.mjs','src/verified/policy.ts','src/core/interval.ts','src/core/heat-certificate.ts','src/core/normalization.ts','src/verified/generated/control.js']){
      const file=join(dir,path),original=readFileSync(file,'utf8');writeFileSync(file,original+'\n');
      expect((await gate(dir,'--artifact')).stderr).toContain('artifact is stale');writeFileSync(file,original);
    }
  });
  it('rejects a missing required law rather than silently shrinking coverage',async()=>{
    const dir=fixture();change(dir,'proofs/laws.mjs',"d.law('scope_wins'","d.law('renamed_scope_wins'");
    expect((await gate(dir)).stderr).toContain('Proof ledger mismatch');
  });
  it('refuses a false column-normalization witness',async()=>{
    const dir=fixture(),file=join(dir,'proofs/heat.mjs');
    writeFileSync(file,readFileSync(file,'utf8')+'\ntransport.run({leaf:{mass:2,weightSum:1}},{denominator:2});\n');
    expect((await gate(dir,'--write')).status).toBe(1);
  });
  it('rejects incompatible ABI declarations',async()=>{
    const dir=fixture(),file=join(dir,'proofs/kernel-abi.json');const abi=JSON.parse(readFileSync(file,'utf8'));abi.shownCount.unshift(['extra','number']);writeFileSync(file,JSON.stringify(abi));
    expect((await gate(dir,'--write')).stderr).toContain('Incompatible kernel ABI');
  });
  it.each(['import fs from "node:fs";','const p = process.pid;','const f = new Function("return 1");'])('refuses effectful proof sources: %s',async source=>{
    const dir=fixture(),file=join(dir,'proofs/heat.mjs');writeFileSync(file,readFileSync(file,'utf8')+'\n'+source);
    expect((await gate(dir,'--write')).status).toBe(1);
  });
  it.each(['const foreign = x => x.facts(() => ({}));','const foreign = x => x.fns({});'])('rejects assumed foreign arithmetic: %s',async source=>{
    const dir=fixture(),file=join(dir,'proofs/streams.mjs');
    writeFileSync(file,readFileSync(file,'utf8')+'\n'+source);
    expect((await gate(dir,'--write')).stderr).toContain('assumed foreign facts are forbidden');
  });
  it('rejects proof imports through an escaping symlink',async()=>{
    const dir=fixture();symlinkSync(join(fixture(),'proofs/heat.mjs'),join(dir,'proofs/outside.mjs'));
    const file=join(dir,'proofs/heat.mjs');writeFileSync(file,readFileSync(file,'utf8')+'\nimport "./outside.mjs";');
    expect((await gate(dir)).stderr).toContain('must stay inside');
  });
});
